//! Opt-in JSON bodies for Tower payment responses.

use super::*;

/// A payment layer configured to return RFC 9457 JSON error bodies.
///
/// Created by [`PaymentLayer::with_problem_details`] or
/// [`PaymentBodyLayer::with_problem_details`]. The callback converts serialized
/// JSON bytes into the application's response body type. Cloning a layer shares
/// the callback; the callback itself does not need to implement `Clone`.
pub struct ProblemDetailsLayer<L, F> {
    inner: L,
    body: Arc<F>,
}

impl<L, F> ProblemDetailsLayer<L, F> {
    pub(super) fn new(inner: L, body: F) -> Self {
        Self {
            inner,
            body: Arc::new(body),
        }
    }
}

impl<L: Clone, F> Clone for ProblemDetailsLayer<L, F> {
    fn clone(&self) -> Self {
        Self {
            inner: self.inner.clone(),
            body: Arc::clone(&self.body),
        }
    }
}

impl<S, L: tower_layer::Layer<S>, F> tower_layer::Layer<S> for ProblemDetailsLayer<L, F> {
    type Service = ProblemDetailsService<L::Service, F>;

    fn layer(&self, inner: S) -> Self::Service {
        ProblemDetailsService {
            inner: self.inner.layer(inner),
            body: Arc::clone(&self.body),
        }
    }
}

/// Tower service that adds Problem Details bodies to payment-layer responses.
///
/// The inner application's response body, headers, and errors are preserved.
/// Only responses generated by the payment layer receive JSON bodies and
/// `Content-Type: application/problem+json`.
pub struct ProblemDetailsService<S, F> {
    inner: S,
    body: Arc<F>,
}

impl<S: Clone, F> Clone for ProblemDetailsService<S, F> {
    fn clone(&self) -> Self {
        Self {
            inner: self.inner.clone(),
            body: Arc::clone(&self.body),
        }
    }
}

impl<S, F, ReqBody, ResBody> tower_service::Service<Request<ReqBody>>
    for ProblemDetailsService<S, F>
where
    S: tower_service::Service<Request<ReqBody>, Response = Response<ResBody>>,
    S::Future: Send + 'static,
    F: Fn(Bytes) -> ResBody + Send + Sync + 'static,
    ResBody: Default + Send + 'static,
{
    type Response = Response<ResBody>;
    type Error = S::Error;
    type Future = Pin<Box<dyn Future<Output = Result<Self::Response, Self::Error>> + Send>>;

    fn poll_ready(&mut self, cx: &mut Context<'_>) -> Poll<Result<(), Self::Error>> {
        self.inner.poll_ready(cx)
    }

    fn call(&mut self, request: Request<ReqBody>) -> Self::Future {
        let future = self.inner.call(request);
        let body = Arc::clone(&self.body);
        Box::pin(async move {
            let mut response = future.await?;
            if let Some(ProblemDetails(mut problem)) = response.extensions_mut().remove() {
                // Match the Axum response's first-offer association. Do not
                // change the challenge headers or require custom verifiers to
                // provide a parseable challenge just to build their response.
                if let Some(challenge) = response
                    .headers()
                    .get_all(WWW_AUTHENTICATE_HEADER)
                    .iter()
                    .filter_map(|value| value.to_str().ok())
                    .flat_map(|value| crate::protocol::core::parse_www_authenticate_all([value]))
                    .find_map(Result::ok)
                {
                    problem.challenge_id = Some(challenge.id);
                }
                match serde_json::to_vec(&problem) {
                    Ok(json) => {
                        *response.body_mut() = body(Bytes::from(json));
                        response.headers_mut().insert(
                            header::CONTENT_TYPE,
                            HeaderValue::from_static("application/problem+json"),
                        );
                    }
                    Err(_) => {
                        *response.status_mut() = StatusCode::INTERNAL_SERVER_ERROR;
                        *response.body_mut() = ResBody::default();
                        response.headers_mut().remove(WWW_AUTHENTICATE_HEADER);
                        response.headers_mut().remove(header::CONTENT_TYPE);
                    }
                }
            }
            Ok(response)
        })
    }
}

